package com.zenius.one.modules.marketing;

import com.zenius.one.platform.common.TenantScopedEntity;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Table;

@Entity
@Table(name = "mkt_segments")
public class MktSegmentEntity extends TenantScopedEntity {

    @Column(name = "name", nullable = false, length = 120)
    private String name;

    @Column(name = "description", length = 255)
    private String description;

    @Column(name = "filter_tag", length = 64)
    private String filterTag;

    @Column(name = "filter_source", length = 64)
    private String filterSource;

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getFilterTag() {
        return filterTag;
    }

    public void setFilterTag(String filterTag) {
        this.filterTag = filterTag;
    }

    public String getFilterSource() {
        return filterSource;
    }

    public void setFilterSource(String filterSource) {
        this.filterSource = filterSource;
    }
}

